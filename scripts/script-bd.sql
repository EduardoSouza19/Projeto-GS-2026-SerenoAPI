CREATE TABLE ESTACOES (
    ID          NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME        NVARCHAR2(100) NOT NULL,
    LINHA       NVARCHAR2(60)  NOT NULL,
    ENDERECO    NVARCHAR2(200) NOT NULL,
    LATITUDE    BINARY_DOUBLE,
    LONGITUDE   BINARY_DOUBLE,
    CONSTRAINT PK_ESTACOES PRIMARY KEY (ID)
);

CREATE TABLE EQUIPAMENTOS (
    ID            NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ESTACAO_ID    NUMBER(10)     NOT NULL,
    TIPO          NVARCHAR2(20)  NOT NULL,
    LOCALIZACAO   NVARCHAR2(150) NOT NULL,
    STATUS_ATUAL  NVARCHAR2(20)  NOT NULL,
    ATUALIZADO_EM TIMESTAMP(7)   NOT NULL,
    CONSTRAINT PK_EQUIPAMENTOS PRIMARY KEY (ID),
    CONSTRAINT FK_EQUIPAMENTOS_ESTACOES FOREIGN KEY (ESTACAO_ID) REFERENCES ESTACOES (ID) ON DELETE CASCADE,
    CONSTRAINT CK_EQUIPAMENTOS_TIPO CHECK (TIPO IN ('ELEVADOR', 'ESCADA_ROLANTE', 'RAMPA', 'PLATAFORMA')),
    CONSTRAINT CK_EQUIPAMENTOS_STATUS CHECK (STATUS_ATUAL IN ('FUNCIONANDO', 'PARADO', 'EM_MANUTENCAO'))
);

CREATE INDEX IX_EQUIPAMENTOS_ESTACAO_ID ON EQUIPAMENTOS (ESTACAO_ID);

CREATE TABLE REPORTES (
    ID              NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    EQUIPAMENTO_ID  NUMBER(10)     NOT NULL,
    USUARIO_ID      NUMBER(10),
    STATUS          NVARCHAR2(20)  NOT NULL,
    OBSERVACAO      NVARCHAR2(300),
    CRIADO_EM       TIMESTAMP(7)   NOT NULL,
    CONSTRAINT PK_REPORTES PRIMARY KEY (ID),
    CONSTRAINT FK_REPORTES_EQUIPAMENTOS FOREIGN KEY (EQUIPAMENTO_ID) REFERENCES EQUIPAMENTOS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_REPORTES_STATUS CHECK (STATUS IN ('FUNCIONANDO', 'PARADO', 'EM_MANUTENCAO'))
);

CREATE INDEX IX_REPORTES_EQUIPAMENTO_ID ON REPORTES (EQUIPAMENTO_ID);

CREATE TABLE IDEMPOTENCY_RECORDS (
    ID                 NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CHAVE              NVARCHAR2(100)  NOT NULL,
    USUARIO_ID         NUMBER(10)      NOT NULL,
    HASH_DO_CORPO      NVARCHAR2(64)   NOT NULL,
    STATUS             NUMBER(10)      NOT NULL,
    CORPO_DA_RESPOSTA  NVARCHAR2(2000) NOT NULL,
    CRIADO_EM          TIMESTAMP(7)    NOT NULL,
    CONSTRAINT PK_IDEMPOTENCY_RECORDS PRIMARY KEY (ID)
);

CREATE UNIQUE INDEX IX_IDEMPOTENCY_CHAVE_USUARIO ON IDEMPOTENCY_RECORDS (CHAVE, USUARIO_ID);

